"use strict";

// Review is local; all mutations go through founder-authenticated callables.
// No Admin SDK, service account, or rules bypass.
const fs = require("node:fs");

const HELP = `Founder resistance vocabulary review:
Setup: operator grants the server-only Firebase Auth custom claim
fieldContentAdmin=true only to the user-confirmed founder UID; refresh the token.
Set FIREBASE_PROJECT_ID and MINERAL_FOUNDER_ID_TOKEN in your local environment.
The token must be a fresh Firebase Auth ID token for that UID (never commit it).
Approved shared offering practitionerContent/resistance_resistance must exist.

1. node scripts/resistance-vocabulary.cjs draft > /tmp/resistance-draft.json
2. node scripts/resistance-vocabulary.cjs review /tmp/resistance-draft.json
   Review every EXACT key and term. Matching uses the existing stemmed phrase
   detector, not an exact-string-only detector. Drafts are not active.
   The same draft is in Firebase Console > Firestore >
   resistanceVocabularyProposals/{proposalId}; do not edit or approve in Console.
3. Preview approval without any network request or write:
   node scripts/resistance-vocabulary.cjs approve /tmp/resistance-draft.json --dry-run
4. ONLY after review (version must exactly match the reviewed version):
   node scripts/resistance-vocabulary.cjs approve /tmp/resistance-draft.json --approve 1

Approval creates new resistance motifLexicon entries, preserves existing entries
and offering copy, and rebuilds the founder's patterns. If rebuilding fails,
retry the same approval. No passages are generated by this tool.
One AI vocabulary invocation per UTC day, including failed attempts.
Changing a file or proposal invalidates its hash; draft again on another day.`;

async function call(name, data) {
  const project = process.env.FIREBASE_PROJECT_ID;
  const token = process.env.MINERAL_FOUNDER_ID_TOKEN;
  if (!project || !/^[a-z0-9-]+$/.test(project) || !token) {
    throw new Error("Set FIREBASE_PROJECT_ID and MINERAL_FOUNDER_ID_TOKEN locally.");
  }
  const response = await fetch(`https://us-central1-${project}.cloudfunctions.net/${name}`, {
    method: "POST",
    headers: { Authorization: `Bearer ${token}`, "Content-Type": "application/json" },
    body: JSON.stringify({ data }),
    signal: AbortSignal.timeout(310000),
  });
  const result = await response.json();
  if (!response.ok || result.error) {
    throw new Error(result.error?.message || `Callable failed (HTTP ${response.status}).`);
  }
  return result.result;
}

async function main() {
  const [command, file, confirm, version] = process.argv.slice(2);
  if (!command || ["--help", "help"].includes(command)) return console.log(HELP);
  if (command === "draft" && !file) {
    return console.log(JSON.stringify(await call("draftResistanceVocabulary", {}), null, 2));
  }
  if (!["review", "approve"].includes(command) || !file) throw new Error(HELP);
  const proposal = JSON.parse(fs.readFileSync(file, "utf8"));
  const { validateEntries, digest } = require("../functions/resistanceVocabulary");
  const entries = validateEntries(proposal.entries);
  if (proposal.version !== 1 || proposal.status !== "draft" ||
      digest({ version: proposal.version, entries }) !== proposal.proposalHash) {
    throw new Error("Invalid or edited proposal file; fetch and review the exact draft.");
  }
  if (command === "review") return console.log(JSON.stringify(proposal, null, 2));
  const approval = {
    proposalId: proposal.proposalId,
    version: proposal.version,
    proposalHash: proposal.proposalHash,
    confirm: "APPROVE_EXACT_RESISTANCE_VOCABULARY",
  };
  if (confirm === "--dry-run") return console.log(JSON.stringify({ dryRun: true, entries, approval }, null, 2));
  if (confirm !== "--approve" || version !== String(proposal.version)) {
    throw new Error("Explicit --approve VERSION must match the reviewed version.");
  }
  console.log(JSON.stringify(await call("approveResistanceVocabulary", approval), null, 2));
}

main().catch((error) => { console.error(error.message); process.exitCode = 1; });